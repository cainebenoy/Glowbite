// Regenerates supabase/seed.sql from DEFAULT_SETTINGS (the one source of seed defaults).
// Run: pnpm tsx scripts/gen-seed.ts
import { writeFileSync } from "node:fs";
import { DEFAULT_SETTINGS } from "../lib/settings";

const json = JSON.stringify(DEFAULT_SETTINGS, null, 2).replace(/'/g, "''");
const sql = `-- Seed: default site settings. Generated by scripts/gen-seed.ts from lib/settings.ts — do not edit by hand.
-- Every claim gate starts OFF. Admins are seeded from ADMIN_EMAILS by scripts/seed-admins.ts.

insert into public.settings (id, data)
values (1, '${json}'::jsonb)
on conflict (id) do nothing;

insert into public.settings_ops (id, team_notify_emails)
values (1, '{}')
on conflict (id) do nothing;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("wrote supabase/seed.sql");
